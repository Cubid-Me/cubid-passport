CREATE OR REPLACE FUNCTION "public"."create_user_check_family"("p_uniquevalue" "text", "p_stamptype" smallint, "p_dapp_id" bigint) RETURNS TABLE("user_id" bigint, "dapp_id" bigint, "created_at" timestamp with time zone, "master_auth_uniquevalue" "text", "uuid" "uuid", "is_authorized" boolean)
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    RETURN QUERY
    WITH user_data AS (
        SELECT u.id AS user_id, s.uniquevalue, s.stamptype, u.parent
        FROM public.stamps s
        JOIN public.users u ON s.created_by_user_id = u.id
        WHERE s.uniquevalue = p_uniquevalue AND s.stamptype = p_stamptype
    ),
    parent_users AS (
        SELECT DISTINCT u.id AS parent_user_id, ud.uniquevalue, ud.stamptype
        FROM user_data ud
        JOIN public.users u ON ud.parent = u.id
    ),
    sibling_users AS (
        SELECT DISTINCT u.id AS sibling_user_id, ud.uniquevalue, ud.stamptype
        FROM user_data ud
        JOIN public.users u ON ud.parent = u.parent
        WHERE u.id <> ud.user_id
    ),
    children_users AS (
        SELECT DISTINCT u.id AS child_user_id, ud.uniquevalue, ud.stamptype
        FROM user_data ud
        JOIN public.users u ON u.parent = ud.user_id
    ),
    all_users AS (
        SELECT user_id, uniquevalue, stamptype FROM user_data
        UNION
        SELECT parent_user_id AS user_id, uniquevalue, stamptype FROM parent_users
        UNION
        SELECT sibling_user_id AS user_id, uniquevalue, stamptype FROM sibling_users
        UNION
        SELECT child_user_id AS user_id, uniquevalue, stamptype FROM children_users
    )
    SELECT DISTINCT au.user_id, du.dapp_id, du.created_at, du.master_auth_uniquevalue, du.uuid, du.is_authorized
    FROM all_users au
    LEFT JOIN public.dapp_users du ON au.user_id = du.user_id AND du.dapp_id = p_dapp_id;
END;
$$;


