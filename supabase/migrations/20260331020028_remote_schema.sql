CREATE OR REPLACE FUNCTION "public"."assign_secret_number"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    -- Select the count of secrets for the user and assign the next sequential number
    NEW.secret_sequential_id := (
        SELECT COALESCE(MAX(secret_sequential_id), 0) + 1
        FROM dapp_user_secrets
        WHERE dapp_user_uuid = NEW.dapp_user_uuid
    );
    RETURN NEW;
END;
$$;


