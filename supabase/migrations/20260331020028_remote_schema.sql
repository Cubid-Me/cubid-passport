   FROM ((("public"."stamps" "s"
     LEFT JOIN "public"."all_greylisted_stamps" "g" ON (("s"."type_and_uniquehash" = "g"."type_and_uniquehash")))
     LEFT JOIN "public"."all_whitelisted_stamps" "w" ON (("s"."type_and_uniquehash" = "w"."type_and_uniquehash")))
     LEFT JOIN "public"."all_users_and_parents" "up" ON (("s"."created_by_user_id" = "up"."id")))
  GROUP BY "s"."type_and_uniquehash",
        CASE
            WHEN ("g"."type_and_uniquehash" IS NOT NULL) THEN 'Blacklisted'::"text"
            WHEN ("w"."type_and_uniquehash" IS NOT NULL) THEN 'Whitelisted'::"text"
            ELSE 'Undefined'::"text"
        END
  ORDER BY "s"."type_and_uniquehash";


