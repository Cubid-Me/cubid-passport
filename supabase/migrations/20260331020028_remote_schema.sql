CREATE OR REPLACE VIEW "public"."all_unique_stamps_expanded" AS
 SELECT "s"."type_and_uniquehash",
    "array_agg"(DISTINCT "us"."status") AS "blacklisted",
    "array_agg"(DISTINCT "s"."id") AS "stanp_ids_distinct",
    "array_agg"(DISTINCT "s"."created_by_user_id") AS "user_ids_distinct",
    "array_agg"(DISTINCT "u"."email") AS "user_emails",
    "array_agg"(DISTINCT "s"."created_by_app") AS "app_ids_distinct",
    "array_agg"(DISTINCT "s"."stamptype") AS "stamptype",
    "array_agg"(DISTINCT "s"."uniquevalue") AS "uniquevalue",
    "array_agg"(DISTINCT "s"."stamp_json") AS "stamp_json"
   FROM (("public"."stamps" "s"
     JOIN "public"."all_unique_stamps" "us" ON (("s"."type_and_uniquehash" = "us"."type_and_uniquehash")))
     LEFT JOIN "public"."users" "u" ON (("s"."created_by_user_id" = "u"."id")))
  GROUP BY "s"."type_and_uniquehash";


